object NegotiationBriefExporter {

  fun buildPricingBriefText(estimate: PricingEstimate): String = buildString {
    val s = estimate.spec
    val targetOffer = estimate.lowPriceKes
    val ceiling = estimate.highPriceKes
    val odoReport = KenyanMarketAnalyticsEngine.evaluateOdometerSanity(s.year, s.mileageKm, s.importStatus)

    appendLine("HEKIMA AUTO — VALUATION & NEGOTIATION BRIEF")
    appendLine("${s.make} ${s.model} ${s.year} (${s.engineCc}cc ${s.fuelType}, ${s.transmission})")
    appendLine("Spec: ${"%,d".format(s.mileageKm)} km | ${s.importStatus} | ${s.condition} condition")
    appendLine()
    appendLine("FAIR KES VALUATION")
    appendLine("• Fair Market Value: ${KenyanMarketAnalyticsEngine.formatKes(estimate.estimatedPriceKes)}")
    appendLine("• Opening Offer Target: ${KenyanMarketAnalyticsEngine.formatKes(targetOffer)}")
    appendLine("• Walk-Away Ceiling: ${KenyanMarketAnalyticsEngine.formatKes(ceiling)}")
    appendLine("• Comparable Peer Avg: ${KenyanMarketAnalyticsEngine.formatKes(estimate.comparableAverageKes)}")
    appendLine("• Est. Depreciation: ${String.format(Locale.US, "%.1f", estimate.annualDepreciationPct)}%/yr")
    appendLine()
    appendLine("KEY PRICE DRIVERS")
    estimate.factorImpacts.forEach { f ->
      val sign = if (f.impactKes >= 0) "+" else "-"
      appendLine("• ${f.factorName}: ${sign}KES ${"%,d".format(kotlin.math.abs(f.impactKes))} (${f.detail})")
    }
    estimate.kraDutyEstimate?.let { kra ->
      appendLine()
      appendLine("KENYA IMPORT & LANDED BENCHMARK")
      appendLine("• 8-Year Rule: ${kra.ageRuleHeadline}")
      appendLine("• Est. KRA Taxes: ${KenyanMarketAnalyticsEngine.formatKes(kra.totalKraTaxesKes)} | Mombasa Landed: ${KenyanMarketAnalyticsEngine.formatKes(kra.mombasaLandedCostKes)}")
    }
    estimate.tcoEstimate?.let { tco ->
      appendLine("• 5-Yr Total Cost of Ownership: ${KenyanMarketAnalyticsEngine.formatKes(tco.totalFiveYearTcoKes)} (${KenyanMarketAnalyticsEngine.formatKes(tco.effectiveMonthlyTcoKes)}/mo)")
    }
    appendLine()
    appendLine("ODOMETER & AUCTION SANITY CHECK")
    appendLine("• Status: ${odoReport.status.badgeLabel} — ${odoReport.headline}")
    if (odoReport.status != OdometerSanityStatus.PLAUSIBLE) {
      appendLine("• Action: Request JEVIC/QISJ certificate & Japanese auction sheet before deposit.")
    }
    if (estimate.comparableListings.isNotEmpty()) {
      appendLine()
      appendLine("COMPARABLE KENYAN LISTINGS")
      estimate.comparableListings.take(4).forEach { comp ->
        appendLine("• ${comp.fullName} (${comp.location}, ${"%,d".format(comp.mileageKm)} km): ${KenyanMarketAnalyticsEngine.formatKes(comp.askingPriceKes)}")
      }
    }
    appendLine()
    appendLine("Advisory estimate generated by Hekima Auto.")
  }

  fun buildComparisonBriefText(verdict: ComparisonVerdict): String = buildString {
    appendLine("HEKIMA AUTO — MULTI-VEHICLE COMPARISON BRIEF")
    appendLine("Strongest Resale Pick: ${verdict.strongestResaleVehicle}")
    appendLine(verdict.verdictExplanation)
    appendLine()
    appendLine("SIDE-BY-SIDE BENCHMARKS")
    verdict.metrics.forEach { m ->
      val v = m.vehicle
      val ageStatus = KenyanMarketAnalyticsEngine.evaluateImportAgeRule(v.year).label
      val odoStatus = KenyanMarketAnalyticsEngine.evaluateOdometerSanity(v.year, v.mileageKm, v.importStatus).status.badgeLabel
      appendLine("• ${v.fullName} (${v.location}, ${v.importStatus})")
      appendLine("  Asking: ${KenyanMarketAnalyticsEngine.formatKes(v.askingPriceKes)} | ${"%,d".format(v.mileageKm)} km ($odoStatus)")
      appendLine("  5-Yr Resale: ${KenyanMarketAnalyticsEngine.formatKes(m.fiveYearResaleKes)} (${String.format(Locale.US, "%.1f", m.valueRetentionPct)}% retained) | $ageStatus")
    }
    appendLine()
    appendLine("Always verify JEVIC/QISJ & NTSA TIMS records prior to purchase.")
  }

  fun exportPricingBriefPdf(context: Context, estimate: PricingEstimate): Uri {
    val lines = buildPricingPdfLines(estimate)
    val slug = "${estimate.spec.make}_${estimate.spec.model}_${estimate.spec.year}"
      .lowercase(Locale.US)
      .replace(Regex("[^a-z0-9]+"), "_")
    return writeLinesToPdf(
      context = context,
      fileName = "hekima_brief_${slug}.pdf",
      title = "Valuation & Negotiation Brief",
      subtitle = "${estimate.spec.make} ${estimate.spec.model} ${estimate.spec.year} • ${estimate.confidenceLabel}",
      sections = lines
    )
  }

  fun exportComparisonBriefPdf(context: Context, verdict: ComparisonVerdict): Uri {
    val sections = mutableListOf<Pair<String, List<String>>>()
    sections.add(
      "Resale Winner & Verdict" to listOf(
        "Top Resale Pick: ${verdict.strongestResaleVehicle}",
        verdict.verdictExplanation
      )
    )
    sections.add(
      "Compared Kenyan Listings" to verdict.metrics.map { m ->
        val v = m.vehicle
        val odo = KenyanMarketAnalyticsEngine.evaluateOdometerSanity(v.year, v.mileageKm, v.importStatus)
        "${v.fullName} (${v.location}): ${KenyanMarketAnalyticsEngine.formatKes(v.askingPriceKes)} | " +
          "${"%,d".format(v.mileageKm)} km [${odo.status.badgeLabel}] | " +
          "5y Retained: ${String.format(Locale.US, "%.1f", m.valueRetentionPct)}% (${KenyanMarketAnalyticsEngine.formatKes(m.fiveYearResaleKes)})"
      }
    )
    sections.add(
      "Showroom Negotiation Checklist" to listOf(
        "• Use 5-year retention & mileage-adjusted spread to counter high asking prices.",
        "• Request JEVIC/QISJ inspection certificate & Japanese auction sheet chassis verification.",
        "• Confirm NTSA TIMS ownership history and logbook encumbrance status."
      )
    )
    return writeLinesToPdf(
      context = context,
      fileName = "hekima_comparison_brief.pdf",
      title = "Multi-Vehicle Negotiation Brief",
      subtitle = "Side-by-Side Kenyan Market Comparison (${verdict.metrics.size} units)",
      sections = sections
    )
  }

  fun buildInspectionBriefText(draft: YardInspectionDraft): String = buildString {
    appendLine("HEKIMA AUTO — ON-SITE YARD INSPECTION & OFFER BRIEF")
    appendLine("${draft.vehicleTitle} (${draft.location})")
    appendLine("Scorecard: ${draft.overallScore}/100 (${draft.verdictTier})")
    appendLine("Asking Price: ${KenyanMarketAnalyticsEngine.formatKes(draft.askingPriceKes)}")
    appendLine("Est. Reconditioning Deduction: -${KenyanMarketAnalyticsEngine.formatKes(draft.estimatedRepairKes)}")
    appendLine("Recommended Adjusted Offer: ${KenyanMarketAnalyticsEngine.formatKes(draft.recommendedOfferKes)}")
    appendLine()
    val flagged = draft.items.filter { it.status != InspectionStatus.PASS }
    if (flagged.isEmpty()) {
      appendLine("All ${draft.items.size} yard checkpoints passed with zero deductions.")
    } else {
      appendLine("FLAGGED INSPECTION FINDINGS")
      flagged.forEach { item ->
        appendLine("• [${item.status.label.uppercase(Locale.US)}] ${item.title}: -${KenyanMarketAnalyticsEngine.formatKes(item.effectiveRepairKes)}")
      }
    }
    if (draft.notes.isNotBlank()) {
      appendLine()
      appendLine("Inspector Notes: ${draft.notes.trim()}")
    }
  }

  fun exportInspectionBriefPdf(context: Context, draft: YardInspectionDraft): Uri {
    val flaggedLines = draft.items.filter { it.status != InspectionStatus.PASS }.map { item ->
      "[${item.status.label}] ${item.category} - ${item.title}: Deduction ${KenyanMarketAnalyticsEngine.formatKes(item.effectiveRepairKes)}"
    }.ifEmpty { listOf("All ${draft.items.size} yard checkpoints passed cleanly.") }

    val sections = mutableListOf(
      "Scorecard & Offer Adjustment" to listOf(
        "Inspection Score: ${draft.overallScore}/100 (${draft.verdictTier})",
        "Seller Asking Price: ${KenyanMarketAnalyticsEngine.formatKes(draft.askingPriceKes)}",
        "Estimated Repair Deduction: -${KenyanMarketAnalyticsEngine.formatKes(draft.estimatedRepairKes)}",
        "Recommended Adjusted Offer: ${KenyanMarketAnalyticsEngine.formatKes(draft.recommendedOfferKes)}"
      ),
      "Yard Checklist Findings" to flaggedLines
    )
    if (draft.notes.isNotBlank()) {
      sections.add("Inspector Notes" to listOf(draft.notes.trim()))
    }
    return writeLinesToPdf(
      context = context,
      fileName = "hekima_yard_inspection.pdf",
      title = "Yard Inspection & Offer Brief",
      subtitle = "${draft.vehicleTitle} • ${draft.location} (${draft.overallScore}/100)",
      sections = sections
    )
  }

  fun shareBriefText(context: Context, subject: String, text: String) {
    val intent = Intent(Intent.ACTION_SEND).apply {
      type = "text/plain"
      putExtra(Intent.EXTRA_SUBJECT, subject)
      putExtra(Intent.EXTRA_TEXT, text)
    }
    context.startActivity(Intent.createChooser(intent, "Share Negotiation Brief"))
  }

  fun shareBriefPdf(context: Context, pdfUri: Uri, subject: String) {
    val intent = Intent(Intent.ACTION_SEND).apply {
      type = "application/pdf"
      putExtra(Intent.EXTRA_SUBJECT, subject)
      putExtra(Intent.EXTRA_STREAM, pdfUri)
      addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
    }
    context.startActivity(Intent.createChooser(intent, "Export PDF Brief"))
  }

  private fun buildPricingPdfLines(estimate: PricingEstimate): List<Pair<String, List<String>>> {
    val s = estimate.spec
    val odoReport = KenyanMarketAnalyticsEngine.evaluateOdometerSanity(s.year, s.mileageKm, s.importStatus)
    val sections = mutableListOf<Pair<String, List<String>>>()

    sections.add(
      "Negotiation Anchors (KES)" to listOf(
        "Fair Market Value: ${KenyanMarketAnalyticsEngine.formatKes(estimate.estimatedPriceKes)}",
        "Recommended Opening Offer (Low Range): ${KenyanMarketAnalyticsEngine.formatKes(estimate.lowPriceKes)}",
        "Walk-Away Ceiling (High Range): ${KenyanMarketAnalyticsEngine.formatKes(estimate.highPriceKes)}",
        "Comparable Peer Average: ${KenyanMarketAnalyticsEngine.formatKes(estimate.comparableAverageKes)}",
        "Depreciation Curve: ${String.format(Locale.US, "%.1f", estimate.annualDepreciationPct)}%/yr (${String.format(Locale.US, "%.0f", estimate.cumulativeDepreciationPct)}% cumulative)"
      )
    )

    sections.add(
      "Detected Price Drivers" to estimate.factorImpacts.map { f ->
        val sign = if (f.impactKes >= 0L) "+" else "-"
        "${f.factorName}: ${sign}KES ${"%,d".format(kotlin.math.abs(f.impactKes))} — ${f.detail}"
      }
    )

    val importAndTcoLines = mutableListOf<String>()
    estimate.kraDutyEstimate?.let { kra ->
      importAndTcoLines.add("8-Year Import Rule: ${kra.ageRuleHeadline}")
      importAndTcoLines.add("KRA Taxes Total: ${KenyanMarketAnalyticsEngine.formatKes(kra.totalKraTaxesKes)} | Mombasa Landed: ${KenyanMarketAnalyticsEngine.formatKes(kra.mombasaLandedCostKes)}")
    }
    estimate.tcoEstimate?.let { tco ->
      importAndTcoLines.add("5-Yr Total Cost of Ownership: ${KenyanMarketAnalyticsEngine.formatKes(tco.totalFiveYearTcoKes)} (${KenyanMarketAnalyticsEngine.formatKes(tco.effectiveMonthlyTcoKes)}/mo)")
    }
    if (importAndTcoLines.isNotEmpty()) {
      sections.add("Kenya Import & Ownership Benchmark" to importAndTcoLines)
    }

    sections.add(
      "Odometer & Buyer Inspection Check" to listOf(
        "Status: ${odoReport.status.badgeLabel} — ${odoReport.headline}",
        odoReport.verificationAdvice
      )
    )

    if (estimate.comparableListings.isNotEmpty()) {
      sections.add(
        "Comparable Peer Listings" to estimate.comparableListings.take(5).map { c ->
          val cOdo = KenyanMarketAnalyticsEngine.evaluateOdometerSanity(c.year, c.mileageKm, c.importStatus)
          "${c.fullName} • ${c.location} • ${"%,d".format(c.mileageKm)} km [${cOdo.status.badgeLabel}] — ${KenyanMarketAnalyticsEngine.formatKes(c.askingPriceKes)}"
        }
      )
    }

    return sections
  }

  private fun writeLinesToPdf(
    context: Context,
    fileName: String,
    title: String,
    subtitle: String,
    sections: List<Pair<String, List<String>>>
  ): Uri {
    val dir = File(context.cacheDir, "briefs").apply { mkdirs() }
    val outFile = File(dir, fileName)

    val nativeRendered = runCatching {
      val document = PdfDocument()
      try {
        val pageWidth = 595
        val pageHeight = 842
        val margin = 40f
        val usableWidth = pageWidth - margin * 2

        val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, 1).create()
        val page = document.startPage(pageInfo)
        val canvas = page.canvas

        val headerBgPaint = Paint().apply { color = Color.rgb(15, 23, 42) }
        val brandPaint = Paint().apply {
          color = Color.rgb(56, 189, 248)
          textSize = 10f
          typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val titlePaint = Paint().apply {
          color = Color.WHITE
          textSize = 18f
          typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val subtitlePaint = Paint().apply {
          color = Color.rgb(203, 213, 225)
          textSize = 11f
        }
        val sectionPaint = Paint().apply {
          color = Color.rgb(14, 116, 144)
          textSize = 12f
          typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val bodyPaint = Paint().apply {
          color = Color.rgb(30, 41, 59)
          textSize = 10f
        }
        val dividerPaint = Paint().apply {
          color = Color.rgb(226, 232, 240)
          strokeWidth = 1f
        }

        canvas.drawRect(0f, 0f, pageWidth.toFloat(), 96f, headerBgPaint)
        val dateStr = SimpleDateFormat("dd MMM yyyy", Locale.US).format(Date())
        canvas.drawText("HEKIMA AUTO • KENYA MARKET BRIEF ($dateStr)", margin, 30f, brandPaint)
        canvas.drawText(title, margin, 56f, titlePaint)
        canvas.drawText(subtitle, margin, 76f, subtitlePaint)

        var y = 122f
        for ((sectionTitle, lines) in sections) {
          if (y > pageHeight - 70f) break
          canvas.drawText(sectionTitle.uppercase(Locale.US), margin, y, sectionPaint)
          y += 6f
          canvas.drawLine(margin, y, pageWidth - margin, y, dividerPaint)
          y += 16f

          for (line in lines) {
            for (wrapped in wrapText(line, bodyPaint, usableWidth)) {
              if (y > pageHeight - 40f) break
              canvas.drawText(wrapped, margin, y, bodyPaint)
              y += 14f
            }
            y += 2f
          }
          y += 10f
        }

        document.finishPage(page)
        FileOutputStream(outFile).use { stream ->
          document.writeTo(stream)
        }
      } finally {
        runCatching { document.close() }
      }
    }.isSuccess

    if (!nativeRendered || !outFile.exists() || outFile.length() == 0L) {
      writeFallbackPdf14(outFile, title, subtitle, sections)
    }

    return FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", outFile)
  }

  private fun writeFallbackPdf14(
    outFile: File,
    title: String,
    subtitle: String,
    sections: List<Pair<String, List<String>>>
  ) {
    fun escapePdfText(raw: String): String =
      raw.replace("•", "-")
        .replace("—", "-")
        .replace("–", "-")
        .replace("\\", "\\\\")
        .replace("(", "\\(")
        .replace(")", "\\)")
        .filter { it.code in 32..126 }

    val streamLines = buildString {
      appendLine("BT")
      appendLine("/F1 14 Tf")
      appendLine("40 800 Td")
      appendLine("(${escapePdfText("HEKIMA AUTO - $title")}) Tj")
      appendLine("/F1 10 Tf")
      appendLine("0 -18 Td")
      appendLine("(${escapePdfText(subtitle)}) Tj")
      for ((header, body) in sections) {
        appendLine("0 -18 Td")
        appendLine("(${escapePdfText(header.uppercase(Locale.US))}) Tj")
        for (line in body.take(8)) {
          appendLine("0 -13 Td")
          appendLine("(${escapePdfText(line.take(92))}) Tj")
        }
      }
      appendLine("ET")
    }

    val objects = listOf(
      "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n",
      "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n",
      "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\nendobj\n",
      "4 0 obj\n<< /Length ${streamLines.length} >>\nstream\n${streamLines}endstream\nendobj\n",
      "5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n"
    )

    val pdf = StringBuilder("%PDF-1.4\n")
    val offsets = mutableListOf<Int>()
    for (obj in objects) {
      offsets.add(pdf.length)
      pdf.append(obj)
    }
    val xrefOffset = pdf.length
    pdf.append("xref\n0 ${objects.size + 1}\n")
    pdf.append("0000000000 65535 f \n")
    offsets.forEach { offset ->
      pdf.append(String.format(Locale.US, "%010d 00000 n \n", offset))
    }
    pdf.append("trailer\n<< /Size ${objects.size + 1} /Root 1 0 R >>\n")
    pdf.append("startxref\n$xrefOffset\n%%EOF\n")

    outFile.writeText(pdf.toString(), Charsets.US_ASCII)
  }

  private fun wrapText(text: String, paint: Paint, maxWidth: Float): List<String> {
    if (paint.measureText(text) <= maxWidth) return listOf(text)
    val words = text.split(" ")
    val result = mutableListOf<String>()
    var current = StringBuilder()
    for (word in words) {
      val candidate = if (current.isEmpty()) word else "$current $word"
      if (paint.measureText(candidate) <= maxWidth) {
        current = StringBuilder(candidate)
      } else {
        if (current.isNotEmpty()) result.add(current.toString())
        current = StringBuilder(word)
      }
    }
    if (current.isNotEmpty()) result.add(current.toString())
    return result
  }
